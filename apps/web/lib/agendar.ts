/**
 * Agendamento online — escrita no banco multi-tenant (o furo nº 1 do produto).
 *
 * Fluxo: validação com as regras do domain (`reservarSlot`) contra o banco
 * (o check do wizard no client era só UX), cliente por telefone (upsert) e
 * INSERT com o invariante de slot único também no banco (UNIQUE
 * tenant_id+funcionario+data+hora — espelha `agendamentos_slot_unico` do
 * schema de produção).
 *
 * ⚠️ Assim como o onboarding, o INSERT é no formato do dev (pg-mem: ids text,
 * PK composta). Em produção (`DATABASE_URL`), o agendamento deve ser criado
 * pela API com ids gerados (`GENERATED BY DEFAULT AS IDENTITY`) — mesmo
 * contrato de validação, ver Fase 7.
 */
import { sql } from 'drizzle-orm';
import { HorarioIndisponivelError, reservarSlot } from '@barbearia/domain';
import { db } from './db';
import { garantirSeed } from './seed';
import { buscarAgendamentos, buscarSiteData } from './repo';

export interface InputAgendamentoOnline {
  tenantSlug: string;
  nome: string;
  telefone: string;
  funcionarioId: string;
  /** 'YYYY-MM-DD' */
  data: string;
  /** 'HH:mm' */
  hora: string;
  servicoNome: string;
}

export interface ResultadoAgendamento {
  ok: boolean;
  erro?: string;
  id?: string;
}

/** Escapa valor p/ SQL inline (dados validados/controlados do servidor). */
function esc(v: unknown): string {
  if (v === null || v === undefined) return 'NULL';
  const s = String(v);
  return `'${s.replace(/'/g, "''")}'`;
}

async function buscarServicoId(tenantSlug: string, nome: string): Promise<string | undefined> {
  const r = await db.execute(
    sql.raw(`SELECT id FROM servicos WHERE tenant_id = ${esc(tenantSlug)} AND nome = ${esc(nome)} LIMIT 1`),
  );
  const l = r.rows[0] as { id?: unknown } | undefined;
  return l ? String(l.id) : undefined;
}

/** Cliente por telefone (upsert): online, o telefone é o identificador. */
async function buscarOuCriarCliente(
  tenantSlug: string,
  nome: string,
  telefone: string,
): Promise<string> {
  const existente = await db.execute(
    sql.raw(
      `SELECT id FROM clientes WHERE tenant_id = ${esc(tenantSlug)} AND telefone = ${esc(telefone)} LIMIT 1`,
    ),
  );
  const linha = existente.rows[0] as { id?: unknown } | undefined;
  if (linha?.id) return String(linha.id);

  const id = `cli-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
  const hoje = new Date().toISOString().slice(0, 10);
  await db.execute(
    sql.raw(`INSERT INTO clientes
      (id, tenant_id, nome, telefone, endereco, data_nasc, data_cad, cartoes, data_retorno, ultimo_servico, alertado)
      VALUES (${esc(id)}, ${esc(tenantSlug)}, ${esc(nome)}, ${esc(telefone)}, NULL, NULL,
              ${esc(hoje)}, 0, NULL, 0, NULL)`),
  );
  return id;
}

/**
 * Valida e grava o agendamento online. Revalida o slot contra o banco no
 * momento da ação (a única checagem que vale) e trata a corrida via UNIQUE.
 */
export async function salvarAgendamentoOnline(
  input: InputAgendamentoOnline,
): Promise<ResultadoAgendamento> {
  await garantirSeed();

  const site = await buscarSiteData(input.tenantSlug);
  if (!site) return { ok: false, erro: 'Barbearia não encontrada.' };

  const funcionario = site.funcionarios.find((f) => f.id === input.funcionarioId);
  const servicoId = await buscarServicoId(input.tenantSlug, input.servicoNome);
  if (!funcionario) return { ok: false, erro: 'Profissional inválido.' };
  if (!servicoId) return { ok: false, erro: 'Serviço inválido.' };

  const nome = input.nome.trim();
  const telefone = input.telefone.trim();
  if (!nome || telefone.length < 8) {
    return { ok: false, erro: 'Preencha nome e telefone válidos.' };
  }

  // invariante central re-validado contra o banco (o check do client era só UX)
  let slot: { data: string; hora: string };
  try {
    slot = reservarSlot(funcionario.escala, input.data, input.hora, await buscarAgendamentos(input.tenantSlug));
  } catch (e) {
    if (e instanceof HorarioIndisponivelError) return { ok: false, erro: e.message };
    return { ok: false, erro: 'Horário indisponível.' };
  }

  const clienteId = await buscarOuCriarCliente(input.tenantSlug, nome, telefone);

  const id = `agen-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
  const hoje = new Date().toISOString().slice(0, 10);
  try {
    await db.execute(
      sql.raw(`INSERT INTO agendamentos
        (id, tenant_id, funcionario, cliente, data, hora, obs, data_lanc, usuario, status, servico)
        VALUES (${esc(id)}, ${esc(input.tenantSlug)}, ${esc(funcionario.id)}, ${esc(clienteId)},
                ${esc(slot.data)}, ${esc(slot.hora)}, NULL, ${esc(hoje)}, '6', 'Agendado', ${esc(servicoId)})`),
    );
  } catch {
    // corrida: alguém ocupou o slot entre a validação e o INSERT
    return { ok: false, erro: 'Este horário acabou de ser ocupado. Escolha outro.' };
  }

  return { ok: true, id };
}
