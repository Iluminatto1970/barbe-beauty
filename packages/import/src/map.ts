/**
 * Mapeamento dump MySQL → Postgres multi-tenant (`packages/db`).
 *
 * Regras aplicadas (decisões documentadas em `packages/db/README.md` e no
 * SAAS_PLANO):
 *  - **tenant_id**: injetado em toda linha de toda tabela de negócio;
 *  - **sentinela `'0000-00-00'`** (MySQL "nunca pago"/data vazia) → `null`
 *    (o Postgres rejeita a data zero; o schema já nasce com esses campos NULLABLE);
 *  - **`dias.dia`** normalizado via `@barbearia/domain` (`'Sabado'` → `'Sábado'`
 *    — bug do legado: o PHP montava o nome sem acento);
 *  - flags `'Sim'/'Não'` e `id` da origem são preservados (identidade
 *    `GENERATED BY DEFAULT` do schema permite inserir ids explícitos — a
 *    migração mantém referências por convenção, como o legado);
 *  - `config` é única por tenant (a linha do dump vira a config do tenant).
 */
import { normalizarDia } from '@barbearia/domain';
import type { TabelaDump } from './parse-dump.js';

export interface Importacao {
  tenantId: string;
  /** tabela → linhas já com `tenant_id`. */
  tabelas: Record<string, Record<string, unknown>[]>;
}

const SENTINELA_DATA_ZERO = '0000-00-00';

/** Campos de data conhecidos que podem carregar o sentinela '0000-00-00'. */
const CAMPOS_DATA: Record<string, string[]> = {
  clientes: ['data_nasc', 'data_cad', 'data_retorno'],
  receber: ['data_lanc', 'data_venc', 'data_pgto'],
  pagar: ['data_lanc', 'data_venc', 'data_pgto'],
  agendamentos: ['data', 'data_cad'],
};

function linhaParaObjeto(tabela: TabelaDump, valores: unknown[]): Record<string, unknown> {
  const obj: Record<string, unknown> = {};
  tabela.colunas.forEach((coluna, i) => {
    obj[coluna] = valores[i];
  });
  return obj;
}

function aplicarRemaps(tabela: TabelaDump, obj: Record<string, unknown>): void {
  // Sentinela de data zero → null
  for (const campo of CAMPOS_DATA[tabela.nome] ?? []) {
    if (obj[campo] === SENTINELA_DATA_ZERO) {
      obj[campo] = null;
    }
  }

  // Bug do legado: 'Sabado' (sem acento) → 'Sábado'
  if (tabela.nome === 'dias' && typeof obj.dia === 'string') {
    obj.dia = normalizarDia(obj.dia);
  }
}

export function mapearImportacao(tenantId: string, tabelas: TabelaDump[]): Importacao {
  const resultado: Importacao = { tenantId, tabelas: {} };

  for (const tabela of tabelas) {
    resultado.tabelas[tabela.nome] = tabela.linhas.map((valores) => {
      const obj = linhaParaObjeto(tabela, valores);
      aplicarRemaps(tabela, obj);
      obj.tenant_id = tenantId;
      return obj;
    });
  }

  return resultado;
}
